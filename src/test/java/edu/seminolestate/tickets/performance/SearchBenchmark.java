package edu.seminolestate.tickets.performance;

import edu.seminolestate.tickets.repository.TicketRepository;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;

public class SearchBenchmark {

    private static final int TICKET_COUNT = 10_000;
    private static final int WARMUP_SEARCHES = 100;
    private static final int MEASURED_SEARCHES = 500;

    public static void main(String[] args) {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.h2.Driver");
        dataSource.setUrl("jdbc:h2:mem:profiling;DB_CLOSE_DELAY=-1");
        dataSource.setUsername("sa");
        dataSource.setPassword("");

        JdbcTemplate jdbc = new JdbcTemplate(dataSource);

        jdbc.execute("""
            CREATE TABLE tickets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                requester_name VARCHAR(255),
                email VARCHAR(255),
                category VARCHAR(100),
                description VARCHAR(4000),
                status VARCHAR(30),
                access_token VARCHAR(100)
            )
            """);

        System.out.println("Generating sample tickets...");

        List<Object[]> rows = new ArrayList<>();
        for (int i = 0; i < TICKET_COUNT; i++) {
            rows.add(new Object[] {
                "User " + i,
                "user" + i + "@example.com",
                "Software",
                i % 10 == 0
                    ? "Printer connection issue on workstation " + i
                    : "General software support request number " + i,
                "OPEN",
                "test-token-" + i
            });
        }

        jdbc.batchUpdate("""
            INSERT INTO tickets
            (requester_name, email, category, description, status, access_token)
            VALUES (?, ?, ?, ?, ?, ?)
            """, rows);

        TicketRepository repo = new TicketRepository(jdbc);

        // Use the same search term before and after optimization.
        String searchTerm = "Printer";

        // Warm up JVM and database operations.
        for (int i = 0; i < WARMUP_SEARCHES; i++) {
            repo.search(searchTerm);
        }

        List<Long> times = new ArrayList<>();
        long totalMatches = 0;

        for (int i = 0; i < MEASURED_SEARCHES; i++) {
            long start = System.nanoTime();
            totalMatches += repo.search(searchTerm).size();
            times.add(System.nanoTime() - start);
        }

        Collections.sort(times);

        double averageMs = times.stream()
            .mapToLong(Long::longValue)
            .average()
            .orElse(0) / 1_000_000.0;

        double medianMs =
            times.get(times.size() / 2) / 1_000_000.0;

        double p95Ms =
            times.get((int) Math.ceil(times.size() * 0.95) - 1)
                / 1_000_000.0;

        System.out.println();
        System.out.println("=== SEARCH PERFORMANCE BASELINE ===");
        System.out.printf(Locale.US, "Tickets: %,d%n", TICKET_COUNT);
        System.out.printf("Search term: %s%n", searchTerm);
        System.out.printf("Warmup searches: %d%n", WARMUP_SEARCHES);
        System.out.printf("Measured searches: %d%n", MEASURED_SEARCHES);
        System.out.printf("Matches per search: %d%n",
            totalMatches / MEASURED_SEARCHES);
        System.out.printf(Locale.US, "Average: %.3f ms%n", averageMs);
        System.out.printf(Locale.US, "Median: %.3f ms%n", medianMs);
        System.out.printf(Locale.US, "95th percentile: %.3f ms%n", p95Ms);
    }
}